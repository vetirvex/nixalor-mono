const ICON_PREFIX = "icon:";
const EMOJI_PREFIX = "emoji:";

type ParsedIcon =
  { type: "icon"; Icon: LucideIcon } | { type: "emoji"; emoji: string } | null;

const parseItemIcon = (value: string | null | undefined): ParsedIcon => {
  if (value?.startsWith(ICON_PREFIX)) {
    const Icon = ICONS_BY_NAME.get(value.slice(ICON_PREFIX.length));
    return Icon ? { type: "icon", Icon } : null;
  }
  if (value?.startsWith(EMOJI_PREFIX)) {
    const emoji = value.slice(EMOJI_PREFIX.length);
    return emoji ? { type: "emoji", emoji } : null;
  }
  return null;
};

/** True for text that is a single emoji (incl. ZWJ sequences and flags). */
const isEmoji = (text: string) =>
  /^(\p{Extended_Pictographic}|\p{Regional_Indicator}{2})(️|‍\p{Extended_Pictographic}|\p{Emoji_Modifier})*$/u.test(
    text.trim()
  );

